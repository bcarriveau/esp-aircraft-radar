inline const uint8_t* radarContactBitmap(AircraftBitmapId id,
                                           uint8_t headingIndex) {
  headingIndex &= (RADAR_CONTACT_HEADING_COUNT - 1U);
  switch (id) {
    case AircraftBitmapId::AIRLINER:
      return RADAR_CONTACT_AIRLINER[headingIndex];
    case AircraftBitmapId::BUSINESS_JET:
      return RADAR_CONTACT_BUSINESS_JET[headingIndex];
    case AircraftBitmapId::TURBOPROP:
      return RADAR_CONTACT_TURBOPROP[headingIndex];
    case AircraftBitmapId::PISTON:
      return RADAR_CONTACT_PISTON[headingIndex];
    case AircraftBitmapId::HELICOPTER:
      return RADAR_CONTACT_HELICOPTER[headingIndex];
    default:
      return RADAR_CONTACT_UNKNOWN[headingIndex];
  }
}

inline bool radarContactPixel(const uint8_t* bitmap, uint8_t x,
                              uint8_t y) {
  if (!bitmap || x >= RADAR_CONTACT_BITMAP_W ||
      y >= RADAR_CONTACT_BITMAP_H) return false;
  const uint8_t packed =
      bitmap[y * RADAR_CONTACT_BITMAP_ROW_BYTES + x / 8U];
  return (packed & (uint8_t)(0x80U >> (x & 7U))) != 0;
}

static_assert((RADAR_CONTACT_HEADING_COUNT &
               (RADAR_CONTACT_HEADING_COUNT - 1U)) == 0,
              "Heading count must remain a power of two");
