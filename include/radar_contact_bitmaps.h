inline const uint8_t* radarContactBitmap(AircraftBitmapId id) {
  switch (id) {
    case AircraftBitmapId::AIRLINER: return RADAR_CONTACT_AIRLINER;
    case AircraftBitmapId::BUSINESS_JET: return RADAR_CONTACT_BUSINESS_JET;
    case AircraftBitmapId::TURBOPROP: return RADAR_CONTACT_TURBOPROP;
    case AircraftBitmapId::PISTON: return RADAR_CONTACT_PISTON;
    case AircraftBitmapId::HELICOPTER: return RADAR_CONTACT_HELICOPTER;
    default: return RADAR_CONTACT_UNKNOWN;
  }
}

inline bool radarContactPixel(const uint8_t* bitmap, uint8_t x, uint8_t y) {
  if (!bitmap || x >= RADAR_CONTACT_BITMAP_W || y >= RADAR_CONTACT_BITMAP_H) return false;
  const uint8_t packed = bitmap[y * RADAR_CONTACT_BITMAP_ROW_BYTES + x / 8];
  return (packed & (uint8_t)(0x80U >> (x & 7U))) != 0;
}
